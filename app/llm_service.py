import os
import json
from openai import AsyncOpenAI
from dotenv import load_dotenv

load_dotenv()

client = AsyncOpenAI(
    api_key=os.getenv("OPENROUTER_API_KEY"),
    base_url="https://openrouter.ai/api/v1"
)

SYSTEM_PROMPT = """Ты — профессиональный B2B-копирайтер и SEO-специалист.
Твоя задача — на основе предоставленных JSON-данных о контрольно-измерительном приборе сгенерировать карточку товара.

СТРОГИЕ ПРАВИЛА:
1. Используй ТОЛЬКО те данные, которые переданы в JSON.
2. КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО выдумывать технические характеристики. Если в JSON нет какого-то параметра, не пиши его.
3. Сформируй блок "Ключевые характеристики". 
   - Определи тип прибора.
   - Составь список из самых важных параметров для этого типа.
   - Проверь наличие каждого параметра в JSON. 
   - Если параметр есть — выведи его.
   - Если параметра нет в JSON — ОБЯЗАТЕЛЬНО напиши: "данных нет".
   - Оформи список строго с новой строки, используя только дефис (-). НЕ используй звездочки (*) и НЕ выделяй названия жирным шрифтом (**).
4. Если в текстовом описании есть незаконченные фразы или каких-то данных не хватает, добавь в конце ответа блок "Требуется уточнение" и укажи, что нужно дописать.
    
ПРАВИЛА ДЛЯ SEO-ОПИСАНИЯ:
- Объем: строго от 800 до 1200 символов.
- НЕ ПЕРЕЧИСЛЯЙ характеристики сухим списком внутри описания. Вместо этого объясняй, для чего нужен прибор, какие задачи он решает, и как его технические особенности помогают в работе.
- Текст должен быть техническим, связным, без "воды" и маркетинговых клише. Избегай повторения одних и тех же фактов разными словами.

СФОРМИРУЙ ОТВЕТ В ФОРМАТЕ MARKDOWN по следующей структуре:
- **SEO-заголовок:** (до 70 символов)
- **SEO-описание:** (по правилам выше)
- **Ключевые характеристики:** (список по правилу №3)
- **Поисковые запросы:** (3-5 запросов)
- **Коммерческий блок:** (Кому подходит, какие задачи решает)
"""


async def generate_product_card(product_data: dict) -> str:
    user_prompt = f"Сгенерируй карточку для следующего товара:\n{json.dumps(product_data, ensure_ascii=False, indent=2)}"

    print("--- ОТПРАВЛЯЕМ ЗАПРОС В OPENROUTER ---")

    try:
        response = await client.chat.completions.create(
            model="nvidia/nemotron-3-ultra-550b-a55b:free",
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt}
            ],
            temperature=0.2
        )
        print("--- ОТВЕТ ПОЛУЧЕН ---")
        print(f"--- ОТВЕТИЛА МОДЕЛЬ: {response.model} ---")
        return response.choices[0].message.content

    except Exception as e:
        print(f"!!! ОШИБКА API: {e} !!!")
        return f"Ошибка: {e}"